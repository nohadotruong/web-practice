-- CREATE

CREATE TABLE users 
(
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	username TEXT UNIQUE NOT NULL,
	fullname TEXT NOT NULL,
	password TEXT NOT NULL,
	role TEXT CHECK (role IN('Manager', 'Cashier')) NOT NULL
);

CREATE TABLE tables
(
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	seating_cap INT CHECK (seating_cap IN (4, 6, 8)) NOT NULL,
	status TEXT DEFAULT 'Available' CHECK (status IN ('Available', 'Occupied'))
);

CREATE TABLE tickets 
(
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL,
	price INT NOT NULL
);

CREATE TABLE invoices (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	date TEXT NOT NULL,
	start_time TEXT NOT NULL,
	end_time TEXT DEFAULT NULL,
	table_id INT NOT NULL,
	subtotal INT NOT NULL,
	vat_percent INT DEFAULT 10,
	vat_amount INT,
	total INT NOT NULL,
	amount_paid INT DEFAULT 0,
	status TEXT DEFAULT 'Unpaid' CHECK (status IN ('Paid', 'Unpaid')) NOT NULL,
	note TEXT
);

CREATE TABLE invoice_details (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id INT REFERENCES invoices(id) ON DELETE CASCADE,
  ticket_id INT NOT NULL,
  quantity INT NOT NULL
);


