-- CREATE

-- USERS
CREATE TABLE roles (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- Admin, Manager, Staff, Customer.
	name_vi TEXT UNIQUE NOT NULL, 
	name_en TEXT UNIQUE NOT NULL
);

CREATE TABLE users (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email TEXT UNIQUE NOT NULL,
	username TEXT UNIQUE NOT NULL,
	fullname TEXT NOT NULL,
	password TEXT NOT NULL,
	phone TEXT UNIQUE NOT NULL,
	role_id INT REFERENCES roles(id) ON DELETE SET NULL
);

-- TOURS
CREATE TABLE nations (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nation_vi TEXT NOT NULL,
	nation_en TEXT NOT NULL
);

CREATE TABLE locations (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name_vi TEXT UNIQUE NOT NULL,
	name_en TEXT UNIQUE NOT NULL,
	nation_id INT REFERENCES nations(id) ON DELETE CASCADE
);

CREATE TABLE tours (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name_vi TEXT NOT NULL,
	name_en TEXT NOT NULL,
	price INT NOT NULL,
	start_date DATE NOT NULL,
	end_date DATE NOT NULL,
	CONSTRAINT check_dates CHECK (end_date >= start_date),
	location_id INT REFERENCES locations(id) ON DELETE CASCADE,
	description_vi TEXT NOT NULL,
	description_en TEXT NOT NULL,
	thumbnail TEXT NOT NULL
);

CREATE TABLE tour_images (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	tour_id INT REFERENCES tours(id) ON DELETE CASCADE,
	url TEXT NOT NULL
);

-- BOOKINGS
CREATE TABLE payment_methods (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name_vi TEXT UNIQUE NOT NULL,
	name_en TEXT UNIQUE NOT NULL
);

CREATE TABLE payment_status (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- Pending - Chờ xử lý / chưa thanh toán
	-- Processsing – Đang xử lý giao dịch
	-- Completed/Paid – Đã thanh toán
	-- Partially Paid – Thanh toán một phần
	-- Failed – Thanh toán thất bại
	-- Cancelled – Thanh toán bị hủy
	-- Refunded – Đã hoàn tiền
	name_vi TEXT UNIQUE NOT NULL,
	name_en TEXT UNIQUE NOT NULL
);

CREATE TABLE booking_status (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- Pending / Awaiting confirmation – Chờ xác nhận
	-- Confirmed – Đã xác nhận
	-- Cancelled – Đã hủy
	-- Completed / Fulfilled – Đã hoàn tất / đã sử dụng dịch vụ
	name_vi TEXT UNIQUE NOT NULL,
	name_en TEXT UNIQUE NOT NULL
);

CREATE TABLE bookings (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INT REFERENCES users(id) ON DELETE SET NULL,
	tour_id INT REFERENCES tours(id) ON DELETE SET NULL,
	booking_date DATE NOT NULL,
	num_persons INT CHECK (num_persons > 0),
	total_price INT NOT NULL,
	payment_method_id INT REFERENCES payment_methods(id) ON DELETE CASCADE,
	payment_status_id INT REFERENCES payment_status(id) ON DELETE CASCADE,
	booking_status_id INT REFERENCES booking_status(id) ON DELETE CASCADE,
	note TEXT
);


