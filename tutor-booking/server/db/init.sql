-- Tạo bảng các môn học
CREATE TABLE subjects (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID tự động tăng, là khóa chính
	name TEXT NOT NULL                                   -- Tên môn học, bắt buộc nhập
);

-- Tạo bảng người dùng, dùng chung cho admin, tutor, student
CREATE TABLE users (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- ID người dùng
	username TEXT UNIQUE NOT NULL,                        -- Tên đăng nhập, duy nhất
	password TEXT NOT NULL,                               -- Mật khẩu
	fullname TEXT NOT NULL,                               -- Họ và tên đầy đủ
	phone TEXT NOT NULL,                                  -- Số điện thoại
	role TEXT CHECK (role IN ('admin', 'tutor', 'student')) NOT NULL, -- Vai trò người dùng: chỉ được là 1 trong 3 giá trị
	subject_id INT REFERENCES subjects(id)                -- Tham chiếu đến bảng subjects (chỉ tutor dùng)
		ON DELETE CASCADE                                 -- Nếu xóa subject, thì user có subject đó cũng bị xóa
		DEFAULT NULL                                       -- Mặc định không có subject
);

-- Tạo bảng lịch học (booking)
CREATE TABLE bookings (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,    -- ID booking tự động tăng

  student_id INT NOT NULL REFERENCES users(id)            -- Người học (student), bắt buộc
    ON DELETE CASCADE,                                    -- Nếu xóa student → xóa luôn lịch học

  tutor_id   INT NOT NULL REFERENCES users(id)            -- Người dạy (tutor), bắt buộc
    ON DELETE CASCADE,                                    -- Nếu xóa tutor → xóa luôn lịch học

  subject_id INT NOT NULL REFERENCES subjects(id)         -- Môn học được học
    ON DELETE CASCADE,                                    -- Nếu xóa môn học → xóa luôn lịch học

  start_date DATE NOT NULL,                               -- Ngày bắt đầu học
  end_date DATE NOT NULL,                                 -- Ngày kết thúc học

  study_time TIME NOT NULL,                               -- Giờ học mỗi buổi (ví dụ: 18:30:00 là 6h30 tối)
  study_days TEXT[] NOT NULL,                             -- Mảng chứa các ngày học (vd: ARRAY['Mon','Wed'])

  duration INT NOT NULL,                                  -- Thời lượng mỗi buổi học (đơn vị: phút)

  status TEXT DEFAULT 'pending'                           -- Trạng thái: mặc định là 'pending'
    CHECK (status IN ('pending', 'confirmed', 'cancelled')) -- Chỉ được chọn trong 3 giá trị
);

