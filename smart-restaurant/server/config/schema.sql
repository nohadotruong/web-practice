CREATE TABLE roles (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL
);

CREATE TABLE users (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email TEXT UNIQUE NOT NULL,
	username TEXT UNIQUE NOT NULL,
	fullname TEXT UNIQUE NOT NULL,
	dob DATE,
	phone TEXT UNIQUE NOT NULL,
	password TEXT NOT NULL,
	role_id INT REFERENCES roles(id) ON DELETE SET NULL
);

CREATE TABLE tables (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	size INT NOT NULL,
	status TEXT DEFAULT 'Available' CHECK (status IN ('Available', 'Occupied'))
);

CREATE TABLE categories (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL
);

CREATE TABLE menu_items (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL,
	description TEXT,
	price INT NOT NULL,
	category_id INT REFERENCES categories(id) ON DELETE SET NULL
);

CREATE TABLE inventory (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL,
	quantity INT NOT NULL,
	unit TEXT NOT NULL,
	price INT NOT NULL
);

CREATE TABLE menu_item_inventory (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	menu_item_id INT REFERENCES menu_items(id) ON DELETE CASCADE,
	inventory_id INT REFERENCES inventory(id) ON DELETE SET NULL,
	quantity INT NOT NULL
);

CREATE TABLE orders (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_date DATE NOT NULL,
	start_time TIME NOT NULL,
	end_time TIME NOT NULL,
	table_id INT REFERENCES tables(id) ON DELETE SET NULL,
	subtotal INT NOT NULL,
	vat_percent INT DEFAULT 10,
	vat_amount INT,
	total INT NOT NULL,
	amount_paid INT DEFAULT 0,
	status TEXT DEFAULT 'Unpaid' CHECK (status IN ('Paid', 'Unpaid')) NOT NULL,
	staff_id INT REFERENCES users(id) ON DELETE SET NULL,
	note TEXT
);

CREATE TABLE order_items (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INT REFERENCES orders(id) ON DELETE CASCADE,
	item_id INT REFERENCES menu_items(id) ON DELETE SET NULL,
	quantity INT NOT NULL DEFAULT 1
);

CREATE TABLE shifts (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INT REFERENCES users(id) ON DELETE CASCADE,
	shift_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
	role_id INT REFERENCES roles(id) ON DELETE SET NULL
);

