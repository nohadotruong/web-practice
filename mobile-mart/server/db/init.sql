-- CREATE
CREATE TABLE users (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email TEXT UNIQUE NOT NULL,
	username TEXT UNIQUE NOT NULL,
	password TEXT NOT NULL,
	fullname TEXT NOT NULL,
	phone TEXT NOT NULL,
	role TEXT DEFAULT 'customer' CHECK (role IN ('admin', 'customer'))  NOT NULL
)

CREATE TABLE brands (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL
);

CREATE TABLE products (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT UNIQUE NOT NULL,
	brand_id INT NOT NULL,
	series TEXT NOT NULL,
	screen_size NUMERIC(3,1) NOT NULL,
	storage INT NOT NULL,
	ram INT NOT NULL,
	os TEXT NOT NULL,
	charging_port TEXT NOT NULL,
	release_date DATE NOT NULL,
	price INT NOT NULL,
	quantity INT NOT NULL,
	status TEXT DEFAULT 'Out of Stock' CHECK (status IN('Out of Stock', 'In Stock')) NOT NULL,
	thumbnail TEXT NOT NULL,
	image1 TEXT NOT NULL,
	image2 TEXT NOT NULL,
	image3 TEXT NOT NULL
);


